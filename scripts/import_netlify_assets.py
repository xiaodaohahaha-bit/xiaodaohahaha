def git_blob_sha(data: bytes) -> str:
    header = f"blob {len(data)}\0".encode()
    return hashlib.sha1(header + data).hexdigest()

def download(item):
    path, expected_sha, expected_size = item
    url = BASE_URL + path.removeprefix("public/")
    target = pathlib.Path(path)
    for attempt in range(4):
        try:
            request = urllib.request.Request(url, headers={"User-Agent": "jc-portfolio-github-import"})
            with urllib.request.urlopen(request, timeout=120) as response:
                data = response.read()
            if len(data) != expected_size:
                raise RuntimeError(f"size mismatch for {path}: {len(data)} != {expected_size}")
            actual_sha = git_blob_sha(data)
            if actual_sha != expected_sha:
                raise RuntimeError(f"hash mismatch for {path}: {actual_sha} != {expected_sha}")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            return path
        except Exception:
            if attempt == 3:
                raise
            time.sleep(2 ** attempt)

def run(*args):
    subprocess.run(args, check=True)

def main():
    with ThreadPoolExecutor(max_workers=8) as pool:
        futures = [pool.submit(download, item) for item in FILES]
        for future in as_completed(futures):
            print(f"downloaded {future.result()}", flush=True)

    pathlib.Path("scripts/import_netlify_assets.py").unlink(missing_ok=True)
    pathlib.Path(".github/workflows/import-netlify-assets.yml").unlink(missing_ok=True)
    run("git", "config", "user.name", "github-actions[bot]")
    run("git", "config", "user.email", "41898282+github-actions[bot]@users.noreply.github.com")
    run("git", "add", "-A")
    run("git", "commit", "-m", "Import portfolio assets")
    run("git", "push", "origin", "HEAD:main")

if __name__ == "__main__":
    main()
